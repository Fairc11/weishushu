"""归档根目录的静态阅读说明：只在缺失时写入，永不覆盖用户已有文件。"""
from __future__ import annotations

import logging
from pathlib import Path

logger = logging.getLogger(__name__)

README_FILENAME = '!请先阅读.txt'

README_TEXT = """\
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

　　　　　　微 博 书 使 用 说 明

　　　　（ 请 先 阅 读 本 文 件 ）

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━


　　这是「微书薯」生成的微博书档案，已经离线保存在你的
　　电脑上，不联网也能看。


【 一、怎么看 】
────────────────────────────

　　1. 双击「微博书.html」：推荐。
　　   可以搜索、看图片、看视频、看评论。

　　2. 「微博书.pdf」：适合打印和长期保存
　　   （备份时选择了保存 PDF 才有）。

　　3. 「微博书.md」：适合导入笔记软件
　　   （备份时选择了保存 Markdown 才有）。


【 二、移动或拷贝（重要） 】
────────────────────────────

　　1. 必须整个文件夹一起移动，
　　   不能只把 HTML 文件单独拷走。

　　2. 图片、视频和数据都在旁边的「数据与媒体」文件夹里，
　　   HTML 离开它们会打不开图片。

　　3. 换电脑、拷 U 盘也一样：整个文件夹一起拷。

　　4. 用网盘或微信传给别人时，建议先把整个文件夹
　　   压缩成一个 zip 再传，避免传输过程中丢文件。


【 三、不要乱动「数据与媒体」 】
────────────────────────────

　　不要重命名、不要删除里面的文件，也不要往里面塞新文件，
　　否则图片会打不开，以后更新备份也可能出错。


【 四、怎么更新内容 】
────────────────────────────

　　不要手动修改这个文件夹里的任何内容。
　　打开微书薯 App，在「微博书库」里点「新增备份」，
　　会自动接着上次的内容继续补。


【 五、换电脑 】
────────────────────────────

　　整个文件夹拷过去就能直接看。
　　登录状态不随档案走，在新电脑上打开微书薯 App
　　重新登录即可。


【 六、不想要了 】
────────────────────────────

　　整个文件夹删除即可，不会影响微书薯 App 和其他微博书。


【 需要帮助 】
────────────────────────────

　　使用微书薯 App 进行新增备份、获取最新版本或反馈问题，
　　请访问：

　　　　https://github.com/Fairc11/weishushu

　　（个别地区的网络可能暂时打不开这个页面，
　　　换个网络环境再试即可。）
"""


def ensure_archive_readme(root) -> Path | None:
    """在归档根目录补一份静态阅读说明；已存在则原样保留。

    写入失败（权限等）只记日志，不影响备份与渲染主流程。
    """
    target = Path(root) / README_FILENAME
    if target.exists():
        return None
    try:
        target.write_text(README_TEXT, encoding='utf-8-sig')
    except OSError as exc:
        logger.warning('写入阅读说明失败：%s', exc)
        return None
    return target
